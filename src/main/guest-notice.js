'use strict';

// Предупреждение «вы не вошли — бои не проверяются».
//
// Когда показывать, решает main, а не окно: окно перезагружается (смена
// масштаба, горячая перезагрузка в разработке), и решение «уже показывали в
// этом запуске» жило бы в нём ровно до первой перезагрузки — человек видел
// бы одно и то же окно по нескольку раз за вечер.
//
// Правило владельца: при запуске без входа — показать; после выхода из
// аккаунта — показать снова; но не чаще одного раза на «отрезок без входа».
// Вошедшему не показывать никогда.

/** Сколько секунд кнопка «Да, я понимаю» остаётся неактивной. */
const COUNTDOWN_SEC = 5;

class GuestNotice {
  /** @param {boolean} signedIn - есть ли вход на момент запуска */
  constructor(signedIn) {
    this.due = !signedIn;
  }

  /** Вошёл — ждать предупреждения больше нечему. */
  signedIn() {
    this.due = false;
  }

  /** Вышел — следующий показ снова положен. */
  signedOut() {
    this.due = true;
  }

  /**
   * Окно спрашивает, показывать ли. Ответ «да» даётся один раз: показ
   * засчитывается в момент вопроса, а не по нажатию кнопки, иначе закрытое
   * крестиком приложение показывало бы его заново после каждой перезагрузки
   * окна.
   * @param {boolean} signedIn - вход прямо сейчас
   */
  take(signedIn) {
    if (signedIn) {
      this.due = false;
      return false;
    }
    const show = this.due;
    this.due = false;
    return show;
  }
}

module.exports = { GuestNotice, COUNTDOWN_SEC };
