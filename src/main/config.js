'use strict';

// Адреса, к которым обращается программа.
//
// Собраны в одном месте по двум причинам. Первая — их было три экземпляра в
// трёх файлах, и разъехаться они могли молча. Вторая — репозиторий клиента
// открытый: тому, кто поднимет свой сервер, не должно приходиться искать
// адрес по коду граблями.
//
// Секретов здесь нет и быть не может. Адрес сервера в настольной программе
// секретом не является в принципе: он виден обычным перехватом трафика, и
// прятать его — самообман. Ключи и токены сюда не кладутся никогда: у
// программы, которая стоит у человека на диске, нет места, где их можно было
// бы спрятать от него самого.

/** Адрес по умолчанию. Переопределяется переменной окружения — для разработки
 *  и для тех, кто поднял свой сервер. */
const SITE = process.env.SIGHTLINE_SITE || 'https://sightline.feelyamon.ru';

module.exports = {
  /** Сайт: правовые страницы, аватарки, страница загрузки. */
  site: SITE,
  /** Корень API. */
  api: `${SITE}/v1`,
  /**
   * Хост, которому разрешено открываться во внешнем браузере и отдавать
   * аватарки. Проверяется отдельно от самого адреса: адрес обновления
   * приходит С СЕРВЕРА, и подменённый ответ не должен уметь открыть человеку
   * что угодно.
   */
  host: new URL(SITE).hostname,
};
