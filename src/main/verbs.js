'use strict';

// Глаголы кил-фида War Thunder. Игра пишет сообщения на языке клиента, поэтому
// держим ru и en рядом. Порядок внутри массивов не важен — парсер сортирует
// по длине, чтобы «тяжело повредил» матчился раньше, чем «повредил».
//
// Если после живого боя в дев-логе всплывают строки в unparsed[] — глагол
// из них дописывается сюда, больше нигде править не нужно.

// Убийство: жертва выбыла, засчитываем kill/death.
const KILL_VERBS = [
  // en
  'destroyed',
  'shot down',
  'wrecked',
  // ru
  'уничтожил',
  'уничтожила',
  'сбил',
  'сбила',
  'разрушил',
  'разрушила',
  // Добивание горящей/подбитой машины. Встречено в живом бою — это засчитанный
  // фраг, а не просто урон.
  'нанёс фатальное повреждение',
  'нанес фатальное повреждение',
  'нанесла фатальное повреждение',
  'has delivered the final blow',
  'dealt a fatal blow',
];

// Не убийство, но обе машины засветились — техника в истории обновляется,
// счётчики не трогаем.
const DAMAGE_VERBS = [
  // en
  'set afire',
  'severely damaged',
  'critically damaged',
  'damaged',
  // ru
  'поджёг',
  'поджег',
  'подожгла',
  'тяжело повредил',
  'тяжело повредила',
  'критически повредил',
  'критически повредила',
  'нанёс критическое повреждение',
  'нанес критическое повреждение',
  'нанесла критическое повреждение',
  'повредил',
  'повредила',
];

// Гибель без участия второго игрока: врезался, утонул, вышел из машины.
// Матчится по одному участнику, засчитываем только death.
const SELF_DEATH_PATTERNS = [
  // en
  /\bhas crashed\b/i,
  /\bhas been wrecked\b/i,
  /\bhas achieved a total loss\b/i,
  /\bhas abandoned\b/i,
  /\bhas drowned\b/i,
  // ru — без \b: в JS он опирается на \w, то есть на латиницу, и рядом с
  // кириллицей никогда не срабатывает. Из-за этого «разбился» не находился.
  /разбил(?:ся|ась)/i,
  /утонул(?:а)?/i,
  /покинул(?:а)? (?:экипаж|машину)/i,
];

// Выход из боя. Такой игрок больше не появится — это ценнее, чем шум, поэтому
// проверяется раньше NOISE_PATTERNS. Техники в этих строках нет, только ник.
const LEFT_PATTERNS = [
  /потерял(?:а)? связь/i,
  /\bhas lost connection\b/i,
  /покинул(?:а)? бой/i,
  /\bhas left the battle\b/i,
];

// Глаголы, которые бывают только про воздух: ими парсер помечает событие,
// а vehicle-class по этой подсказке относит машину к самолётам/вертолётам.
const AIR_VERBS = ['сбил', 'сбила', 'shot down'];

// Строки, которые вообще не про технику: ачивки, серии убийств, захват точек.
// Отбрасываем молча, чтобы не засорять unparsed[].
const NOISE_PATTERNS = [
  /\bhas achieved\b/i,
  /\bhas captured\b/i,
  /\bis capturing\b/i,
  /\bhas been captured\b/i,
  /\bhas connected\b/i,
  /\bhas disconnected\b/i,
  /\bhas won\b/i,
  // Награды приходят как «Ник (Техника) получил "Снайпер"» — кавычки обязательны,
  // иначе шаблон съел бы обычные фразы. Встречено в живом бою.
  /получил(?:а)?\s+["«]/i,
  /получил(?:а)? награду/i,
  /ударил(?:а)? первым/i,
  /\bfirst strike\b/i,
  // Объявления без второго участника: награда за добивание, бортовые сообщения.
  /нанёс(?:ла)? последний удар/i,
  /нанес(?:ла)? последний удар/i,
  /двигатель перегрелся/i,
  /захватил(?:а)?/i,
  /захватывает/i,
  /подключил(?:ся|ась)/i,
  /отключил(?:ся|ась)/i,
  // Дубль дисконнекта: игра шлёт его сырым ключом локализации, без перевода
  // и с обрезанным клан-тегом. Сам факт выхода ловится через LEFT_PATTERNS.
  /NET_PLAYER_DISCONNECT/i,
];

module.exports = {
  KILL_VERBS,
  DAMAGE_VERBS,
  SELF_DEATH_PATTERNS,
  LEFT_PATTERNS,
  NOISE_PATTERNS,
  AIR_VERBS,
};
